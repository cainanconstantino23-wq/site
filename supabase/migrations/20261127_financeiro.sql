create or replace function public.fin_marcar_recebido(p_id bigint, p_recebido boolean) returns void language plpgsql set search_path to '' as $$
begin
  perform public.fin_checar_dono();
  update public.fin_receber set status = case when p_recebido then 'recebido' else 'pendente' end,
    recebido_em = case when p_recebido then public.fin_hoje() end where id = p_id;
end $$;

create or replace function public.fin_marcar_pago(p_id bigint, p_pago boolean) returns void language plpgsql set search_path to '' as $$
begin
  perform public.fin_checar_dono();
  update public.fin_pagar set status = case when p_pago then 'pago' else 'pendente' end,
    pago_em = case when p_pago then public.fin_hoje() end where id = p_id;
end $$;

create or replace function public.fin_marcar_varios_pagos(p_ids bigint[]) returns void language plpgsql set search_path to '' as $$
begin
  perform public.fin_checar_dono();
  update public.fin_pagar set status = 'pago', pago_em = public.fin_hoje() where id = any(p_ids) and status = 'pendente';
end $$;

-- Exclui o recebimento. A distribuição ainda não paga vai junto; a já paga fica.
create or replace function public.fin_excluir_receber(p_id bigint) returns void language plpgsql set search_path to '' as $$
declare r record;
begin
  perform public.fin_checar_dono();
  select recorrente_id, competencia into r from public.fin_receber where id = p_id;
  if r.recorrente_id is not null and r.competencia is not null then
    insert into public.fin_receita_pulada (recorrente_id, competencia) values (r.recorrente_id, r.competencia)
    on conflict do nothing;
  end if;
  delete from public.fin_pagar where receber_id = p_id and status = 'pendente';
  delete from public.fin_receber where id = p_id;
end $$;

-- Contas de recorrência são canceladas (para não voltarem); as demais, excluídas.
create or replace function public.fin_excluir_pagar(p_id bigint) returns void language plpgsql set search_path to '' as $$
begin
  perform public.fin_checar_dono();
  if exists (select 1 from public.fin_pagar where id = p_id and recorrente_id is not null) then
    update public.fin_pagar set status = 'cancelado', pago_em = null where id = p_id;
  else
    delete from public.fin_pagar where id = p_id;
  end if;
end $$;

-- Fechamento: marca como recebidas as contas do cliente vencidas ou deste mês (meses futuros ficam).
create or replace function public.fin_fechar_cliente(p_cliente bigint) returns void language plpgsql set search_path to '' as $$
begin
  perform public.fin_checar_dono();
  update public.fin_receber set status = 'recebido', recebido_em = public.fin_hoje()
  where cliente_id = p_cliente and status = 'pendente'
    and vencimento < to_date(public.fin_somar_mes(public.fin_mes_atual(), 1) || '-01', 'YYYY-MM-DD');
end $$;

create or replace function public.fin_salvar_recorrente(d jsonb) returns bigint language plpgsql set search_path to '' as $$
declare
  v_id bigint := nullif(d->>'id', '')::bigint;
  v_dia int := (d->>'dia')::int;
  v_inicio text := d->>'inicio';
  atual text := public.fin_mes_atual();
begin
  perform public.fin_checar_dono();
  if v_id is null then
    insert into public.fin_recorrentes (descricao, pessoa_id, categoria_id, valor, dia, inicio)
    values (d->>'descricao', nullif(d->>'pessoa_id', '')::bigint, nullif(d->>'categoria_id', '')::bigint,
      (d->>'valor')::bigint, v_dia, v_inicio)
    returning id into v_id;
    return v_id;
  end if;
  update public.fin_recorrentes set descricao = d->>'descricao', pessoa_id = nullif(d->>'pessoa_id', '')::bigint,
    categoria_id = nullif(d->>'categoria_id', '')::bigint, valor = (d->>'valor')::bigint, dia = v_dia, inicio = v_inicio
  where id = v_id;
  -- contas ainda pendentes, deste mês em diante, seguem a recorrência
  update public.fin_pagar set descricao = d->>'descricao', pessoa_id = nullif(d->>'pessoa_id', '')::bigint,
    categoria_id = nullif(d->>'categoria_id', '')::bigint, valor = (d->>'valor')::bigint,
    vencimento = public.fin_venc(competencia, v_dia)
  where recorrente_id = v_id and status = 'pendente' and competencia >= atual;
  delete from public.fin_pagar where recorrente_id = v_id and status = 'pendente' and competencia < v_inicio;
  return v_id;
end $$;

create or replace function public.fin_salvar_receita_recorrente(d jsonb) returns bigint language plpgsql set search_path to '' as $$
declare
  v_id bigint := nullif(d->>'id', '')::bigint;
  v_dia int := (d->>'dia')::int;
  v_inicio text := d->>'inicio';
  v_fim text := nullif(d->>'fim', '');
  atual text := public.fin_mes_atual();
begin
  perform public.fin_checar_dono();
  if v_fim is not null and v_fim < v_inicio then raise exception 'O mês final não pode ser antes do início.'; end if;
  if v_id is null then
    insert into public.fin_receitas_recorrentes (descricao, cliente_id, categoria_id, valor, dia, inicio, fim)
    values (d->>'descricao', nullif(d->>'cliente_id', '')::bigint, nullif(d->>'categoria_id', '')::bigint,
      (d->>'valor')::bigint, v_dia, v_inicio, v_fim)
    returning id into v_id;
    return v_id;
  end if;
  update public.fin_receitas_recorrentes set descricao = d->>'descricao', cliente_id = nullif(d->>'cliente_id', '')::bigint,
    categoria_id = nullif(d->>'categoria_id', '')::bigint, valor = (d->>'valor')::bigint, dia = v_dia,
    inicio = v_inicio, fim = v_fim
  where id = v_id;
  update public.fin_receber set titulo = d->>'descricao', cliente_id = nullif(d->>'cliente_id', '')::bigint,
    categoria_id = nullif(d->>'categoria_id', '')::bigint, valor = (d->>'valor')::bigint,
    vencimento = public.fin_venc(competencia, v_dia)
  where recorrente_id = v_id and status = 'pendente' and competencia >= atual;
  delete from public.fin_receber where recorrente_id = v_id and status = 'pendente' and competencia < v_inicio;
  -- contrato passou a terminar antes: remove os meses depois do fim ainda não recebidos
  if v_fim is not null then
    delete from public.fin_receber where recorrente_id = v_id and status = 'pendente' and competencia > v_fim;
  end if;
  return v_id;
end $$;

create or replace function public.fin_alternar_recorrente(p_id bigint, p_ativo boolean) returns void language plpgsql set search_path to '' as $$
begin
  perform public.fin_checar_dono();
  if p_ativo then
    update public.fin_recorrentes set ativo = true, gerar_desde = public.fin_mes_atual() where id = p_id;
  else
    update public.fin_recorrentes set ativo = false where id = p_id;
    delete from public.fin_pagar where recorrente_id = p_id and status = 'pendente' and competencia > public.fin_mes_atual();
  end if;
end $$;

