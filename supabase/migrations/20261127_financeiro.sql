-- Financeiro (27/11/2026): migrado do app local (Next.js + SQLite) para o site.
-- Só o dono (public.donos) lê e escreve. Valores em centavos. Meses no formato AAAA-MM.
-- Operações que mexem em mais de uma tabela passam pelas funções fin_* (uma transação cada).

-- ------------------------------------------------------------ datas (fuso da Bahia)
create or replace function public.fin_hoje() returns date language sql stable set search_path to '' as $$
  select (now() at time zone 'America/Bahia')::date;
$$;
create or replace function public.fin_mes_atual() returns text language sql stable set search_path to '' as $$
  select to_char(public.fin_hoje(), 'YYYY-MM');
$$;
create or replace function public.fin_somar_mes(mes text, delta int) returns text language sql stable set search_path to '' as $$
  select to_char(to_date(mes || '-01', 'YYYY-MM-DD') + make_interval(months => delta), 'YYYY-MM');
$$;
-- Vencimento no mês, ajustando o dia ao tamanho do mês (31 → 30, 28...)
create or replace function public.fin_venc(mes text, dia int) returns date language sql stable set search_path to '' as $$
  select to_date(mes || '-01', 'YYYY-MM-DD')
    + (least(dia, extract(day from (to_date(mes || '-01', 'YYYY-MM-DD') + interval '1 month - 1 day'))::int) - 1);
$$;

-- ------------------------------------------------------------ tabelas
create table if not exists public.fin_categorias (
  id bigint generated by default as identity primary key,
  nome text not null,
  tipo text not null check (tipo in ('receita', 'despesa')),
  grupo text check (grupo in ('pessoal', 'fixa', 'variavel', 'imposto'))
);

create table if not exists public.fin_clientes (
  id bigint generated by default as identity primary key,
  nome text not null,
  documento text, email text, telefone text, obs text,
  criado_em timestamptz not null default now()
);

-- Equipe (editores, funcionários, freelancers) e fornecedores
create table if not exists public.fin_pessoas (
  id bigint generated by default as identity primary key,
  nome text not null,
  tipo text not null default 'fornecedor' check (tipo in ('editor', 'funcionario', 'freelancer', 'fornecedor')),
  pix text, telefone text, email text, obs text,
  criado_em timestamptz not null default now()
);

-- Despesas que se repetem todo mês
create table if not exists public.fin_recorrentes (
  id bigint generated by default as identity primary key,
  descricao text not null,
  pessoa_id bigint references public.fin_pessoas(id) on delete set null,
  categoria_id bigint references public.fin_categorias(id) on delete set null,
  valor bigint not null check (valor > 0),
  dia int not null check (dia between 1 and 31),
  inicio text not null check (inicio ~ '^\d{4}-\d{2}$'),
  ativo boolean not null default true,
  -- mês a partir do qual a recorrência cria lançamentos sozinha (cadastro ou reativação)
  gerar_desde text not null default public.fin_mes_atual() check (gerar_desde ~ '^\d{4}-\d{2}$')
);

-- Receitas que se repetem todo mês (contratos mensais de clientes)
create table if not exists public.fin_receitas_recorrentes (
  id bigint generated by default as identity primary key,
  descricao text not null,
  cliente_id bigint references public.fin_clientes(id) on delete set null,
  categoria_id bigint references public.fin_categorias(id) on delete set null,
  valor bigint not null check (valor > 0),
  dia int not null check (dia between 1 and 31),
  inicio text not null check (inicio ~ '^\d{4}-\d{2}$'),
  fim text check (fim ~ '^\d{4}-\d{2}$'),   -- último mês; vazio = até cancelar
  ativo boolean not null default true,
  gerar_desde text not null default public.fin_mes_atual() check (gerar_desde ~ '^\d{4}-\d{2}$')
);

create table if not exists public.fin_receber (
  id bigint generated by default as identity primary key,
  cliente_id bigint references public.fin_clientes(id) on delete set null,
  titulo text not null,
  categoria_id bigint references public.fin_categorias(id) on delete set null,
  valor bigint not null check (valor > 0),
  vencimento date not null,
  status text not null default 'pendente' check (status in ('pendente', 'recebido')),
  recebido_em date,
  obs text,
  recorrente_id bigint references public.fin_receitas_recorrentes(id) on delete set null,
  competencia text,
  criado_em timestamptz not null default now(),
  unique (recorrente_id, competencia)
);

create table if not exists public.fin_pagar (
  id bigint generated by default as identity primary key,
  pessoa_id bigint references public.fin_pessoas(id) on delete set null,
  descricao text not null,
  categoria_id bigint references public.fin_categorias(id) on delete set null,
  valor bigint not null check (valor > 0),
  vencimento date not null,
  status text not null default 'pendente' check (status in ('pendente', 'pago', 'cancelado')),
  pago_em date,
  receber_id bigint references public.fin_receber(id) on delete set null,       -- distribuição de um recebimento
  recorrente_id bigint references public.fin_recorrentes(id) on delete set null,
  competencia text,
  obs text,
  criado_em timestamptz not null default now(),
  unique (recorrente_id, competencia)
);

-- Meses em que uma receita recorrente foi excluída (para não ser recriada)
create table if not exists public.fin_receita_pulada (
  recorrente_id bigint not null references public.fin_receitas_recorrentes(id) on delete cascade,
  competencia text not null,
  primary key (recorrente_id, competencia)
);

create index if not exists fin_pagar_venc on public.fin_pagar (vencimento);
create index if not exists fin_pagar_receber on public.fin_pagar (receber_id);
create index if not exists fin_pagar_pessoa on public.fin_pagar (pessoa_id);
create index if not exists fin_pagar_categoria on public.fin_pagar (categoria_id);
create index if not exists fin_receber_venc on public.fin_receber (vencimento);
create index if not exists fin_receber_cliente on public.fin_receber (cliente_id);
create index if not exists fin_receber_categoria on public.fin_receber (categoria_id);
create index if not exists fin_recorrentes_pessoa on public.fin_recorrentes (pessoa_id);
create index if not exists fin_recorrentes_categoria on public.fin_recorrentes (categoria_id);
create index if not exists fin_rr_cliente on public.fin_receitas_recorrentes (cliente_id);
create index if not exists fin_rr_categoria on public.fin_receitas_recorrentes (categoria_id);

-- ------------------------------------------------------------ acesso: só o dono
do $$
declare t text;
begin
  foreach t in array array['fin_categorias', 'fin_clientes', 'fin_pessoas', 'fin_recorrentes',
                           'fin_receitas_recorrentes', 'fin_receber', 'fin_pagar', 'fin_receita_pulada'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists fin_dono on public.%I', t);
    execute format('create policy fin_dono on public.%I for all to authenticated using ((select public.eh_dono())) with check ((select public.eh_dono()))', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;

-- ------------------------------------------------------------ funções
create or replace function public.fin_checar_dono() returns void language plpgsql stable set search_path to '' as $$
begin
  if not coalesce(public.eh_dono(), false) then raise exception 'Sem acesso ao financeiro.'; end if;
end $$;

/* Cria as contas a pagar e os recebimentos das recorrências ativas, de "gerar_desde"
   (ou do início, se for depois) até o mês pedido ou o mês atual — o que vier depois.
   Preenche meses que ninguém abriu; nunca cria nada antes de a recorrência existir. */
create or replace function public.fin_gerar(p_mes text) returns void language plpgsql set search_path to '' as $$
declare
  atual text := public.fin_mes_atual();
  ate text := atual;
  r record; m text; fim text;
begin
  perform public.fin_checar_dono();
  if p_mes ~ '^\d{4}-\d{2}$' and p_mes > atual then ate := least(p_mes, public.fin_somar_mes(atual, 120)); end if;

  for r in select * from public.fin_recorrentes where ativo loop
    m := greatest(r.inicio, r.gerar_desde);
    while m <= ate loop
      insert into public.fin_pagar (descricao, pessoa_id, categoria_id, valor, vencimento, recorrente_id, competencia)
      values (r.descricao, r.pessoa_id, r.categoria_id, r.valor, public.fin_venc(m, r.dia), r.id, m)
      on conflict (recorrente_id, competencia) do nothing;
      m := public.fin_somar_mes(m, 1);
    end loop;
  end loop;

  for r in select * from public.fin_receitas_recorrentes where ativo loop
    m := greatest(r.inicio, r.gerar_desde);
    fim := case when r.fim is not null and r.fim < ate then r.fim else ate end;
    while m <= fim loop
      if not exists (select 1 from public.fin_receita_pulada p where p.recorrente_id = r.id and p.competencia = m) then
        insert into public.fin_receber (titulo, cliente_id, categoria_id, valor, vencimento, recorrente_id, competencia)
        values (r.descricao, r.cliente_id, r.categoria_id, r.valor, public.fin_venc(m, r.dia), r.id, m)
        on conflict (recorrente_id, competencia) do nothing;
      end if;
      m := public.fin_somar_mes(m, 1);
    end loop;
  end loop;
end $$;

-- Recebimento (novo ou edição). "repetir" = vira receita recorrente a partir do mês do vencimento.
create or replace function public.fin_salvar_receber(d jsonb) returns bigint language plpgsql set search_path to '' as $$
declare
  v_id bigint := nullif(d->>'id', '')::bigint;
  v_venc date := (d->>'vencimento')::date;
  v_status text := case when d->>'status' = 'recebido' then 'recebido' else 'pendente' end;
  v_receb date; v_rec bigint; v_mes text; v_novo bigint;
begin
  perform public.fin_checar_dono();
  v_receb := case when v_status = 'recebido' then coalesce(nullif(d->>'recebido_em', '')::date, public.fin_hoje()) end;
  if v_id is not null then
    update public.fin_receber set cliente_id = nullif(d->>'cliente_id', '')::bigint, titulo = d->>'titulo',
      categoria_id = nullif(d->>'categoria_id', '')::bigint, valor = (d->>'valor')::bigint, vencimento = v_venc,
      status = v_status, recebido_em = v_receb, obs = nullif(d->>'obs', '')
    where id = v_id returning recorrente_id into v_rec;
    if not found then raise exception 'Recebimento não encontrado.'; end if;
  else
    insert into public.fin_receber (cliente_id, titulo, categoria_id, valor, vencimento, status, recebido_em, obs)
    values (nullif(d->>'cliente_id', '')::bigint, d->>'titulo', nullif(d->>'categoria_id', '')::bigint,
      (d->>'valor')::bigint, v_venc, v_status, v_receb, nullif(d->>'obs', ''))
    returning id into v_id;
  end if;

  if coalesce((d->>'repetir')::boolean, false) and v_rec is null then
    v_mes := to_char(v_venc, 'YYYY-MM');
    insert into public.fin_receitas_recorrentes (descricao, cliente_id, categoria_id, valor, dia, inicio, gerar_desde)
    values (d->>'titulo', nullif(d->>'cliente_id', '')::bigint, nullif(d->>'categoria_id', '')::bigint,
      (d->>'valor')::bigint, extract(day from v_venc)::int, v_mes, public.fin_mes_atual())
    returning id into v_novo;
    update public.fin_receber set recorrente_id = v_novo, competencia = v_mes where id = v_id;
  end if;
  return v_id;
end $$;

